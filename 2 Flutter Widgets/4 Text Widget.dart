/*
  Text Widget in Flutter:
  -> The Text Widget is used to display a string of text with single style. 
  -> It is one of the most commonly used widgets in Flutter. 
  -> The Text Widget can be customized with various properties such as
  font size, color, weight, and more.

  Example:
  Text(
    'Hello, World!',
    style: TextStyle(
      color: Colors.blue,   //color of the text
      fontSize: 24,         //size of the text
      fontWeight: FontWeight.bold, //weight of the text
      backgroundColor: Colors.yellow, //background color of the text
    ),
  );
*/