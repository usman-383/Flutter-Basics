/*
Row and Column Widgets:
-> Row and Column widgets are used to arrange other widgets in a 
   horizontal or vertical direction respectively.
  -> They are commonly used for creating layouts in Flutter.
  -> The Row widget arranges its children in a horizontal direction,
     while the Column widget arranges its children in a vertical direction.

  Example:
  Row(
    mainAxisAlignment: MainAxisAlignment.spaceEvenly,
    crossAxisAlignment: CrossAxisAlignment.center,
    children: [
      Text('Item 1'),
      Text('Item 2'),
      Text('Item 3'),
    ],
  );

  Column(
    mainAxisAlignment: MainAxisAlignment.spaceEvenly,
    crossAxisAlignment: CrossAxisAlignment.center,
    children: [
      Text('Item 1'),
      Text('Item 2'),
      Text('Item 3'),
    ],
  );
*/ 