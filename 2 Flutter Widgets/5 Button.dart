/*
  Button Widget in Flutter:
  -> The Button Widget is used to create a button that can be pressed 
    by the user.
  -> It is one of the most commonly used widgets in Flutter.
  -> The Button Widget can be customized with various properties such
     as color, size, shape, and more.

  Types of Button Widgets in Flutter:
  1. ElevatedButton: A button that has a raised appearance and is typically
     used for primary actions.
  2. TextButton: A button that has a flat appearance and is typically used
     for secondary actions.
  3. OutlinedButton: A button that has a border and is typically used for
     secondary actions.

  Example:
  ElevatedButton(
    onPressed: () {
      // Do something when the button is pressed
    },
    child: const Text('Press Me'),
  );

  TextButton(
    onPressed: () {
      // Do something when the button is pressed
    },
    child: const Text('Press Me'),
  );

  OutlinedButton(
    onPressed: () {
      // Do something when the button is pressed
    },
    child: const Text('Press Me'),
  );
*/